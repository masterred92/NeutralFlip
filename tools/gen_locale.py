#!/usr/bin/env python3
"""KennyShared 2.0.0: rebuild Locales/enUS.lua from every L["..."] used in the addon's TOC files.
usage: tools/gen_locale.py [--check]   (--check fails if enUS.lua is out of date)"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
toc = next(root.glob("*.toc"))
files = [l.strip().replace("\\", "/") for l in toc.read_text().splitlines() if l.strip().endswith(".lua") and not l.startswith("#")]
keys = set()
for f in files:
    if not f.startswith("Locales/"):
        keys |= set(re.findall(r'L\["((?:[^"\\]|\\.)+)"\]', (root / f).read_text()))
out = ["-- English strings (the default), generated by tools/gen_locale.py. Translators: copy this file to",
       "-- Locales/<locale>.lua, change \"enUS\" to your locale, replace each true with the translation and add",
       "-- the file to the TOC. Any string without a translation falls back to the English text.",
       "local _, ns = ...", 'ns.Core.AddLocale("enUS", {']
out += [f'  ["{k}"] = true,' for k in sorted(keys)] + ["})", ""]
text = "\n".join(out); dest = root / "Locales/enUS.lua"
if "--check" in sys.argv:
    ok = dest.exists() and dest.read_text() == text
    print("enUS.lua up to date" if ok else "enUS.lua OUT OF DATE: run tools/gen_locale.py"); sys.exit(0 if ok else 1)
dest.parent.mkdir(exist_ok=True); dest.write_text(text); print(f"{len(keys)} strings -> {dest}")
